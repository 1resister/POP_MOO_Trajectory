function test_time_vibration_pareto()
%TEST_TIME_VIBRATION_PARETO Check dominance and representative selection.
time=[0.576;0.577;0.578;0.579;0.587];
vibration=[1.40;0.82;0.81;0.85;0.78];
n=numel(time);
pairs=cell(n,1);
for index=1:n
    pairs{index}=struct('suppression',struct('N',575+index), ...
        'no_suppression',struct('N',575+index));
end
sweepData=table((576:580).',time,repmat("[1 1 1 1]",n,1),ones(n,1), ...
    1.8*ones(n,1),vibration,ones(n,1),ones(n,1), ...
    1e-5*ones(n,1),1e-7*ones(n,1),99*ones(n,1), ...
    0.05*ones(n,1),0.05*ones(n,1),true(n,1),true(n,1), ...
    repmat("ok",n,1),repmat("ok",n,1), ...
    'VariableNames',{'N','Time_s','Nvec','LambdaVibration', ...
    'NoSuppressionJvibration','SuppressedJvibration', ...
    'NoSuppressionJstraightness','SuppressedJstraightness', ...
    'NoSuppressionBandEnergy','SuppressedBandEnergy', ...
    'BandReductionPercent','NoSuppressionMaxContourError_mm', ...
    'SuppressedMaxContourError_mm','NoSuppressionFeasible', ...
    'SuppressionFeasible','NoSuppressionStatus','SuppressionStatus'});
[solutions,data,selection]=build_time_vibration_pareto(pairs,sweepData);
assert(numel(solutions)==n);
assert(isequal(find(data.ParetoOptimal).',[1 2 3 5]));
assert(selection.minimum_time_index==1);
assert(selection.knee_index==2);
assert(selection.minimum_vibration_index==5);
assert(data.IsMinimumTime(1) && data.IsKnee(2) && data.IsMinimumVibration(5));
assert(all(isfinite(data.UtopiaDistance(data.ParetoOptimal))));
fprintf('PASS test_time_vibration_pareto (knee T=%.3f s)\n', ...
    data.Time_s(selection.knee_index));
end
