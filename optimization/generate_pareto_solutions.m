function [solutions,data] = generate_pareto_solutions(path,cfg,Nvec,warm, ...
    straightScale,vibrationScale,bandReference)
%GENERATE_PARETO_SOLUTIONS Weighted secondary scan under a hard time epsilon.
if nargin<7 || isempty(bandReference)
    proxy=calculate_resonance_band_proxy(warm,cfg);
    frequency=calculate_frequency_metrics(warm,cfg);
    bandReference=struct('proxy',proxy.total,'actual', ...
        frequency.mode(1).band_energy.modal_x+ ...
        frequency.mode(1).band_energy.modal_y);
    warm=attach_resonance_band_objective(warm,cfg,bandReference,false);
end
weights=unique(cfg.optimization.pareto_weights(:).');
solutions=cell(numel(weights),1);
rows=struct('LambdaVibration',{},'LambdaStraightness',{},'N',{},'T',{}, ...
    'Jvibration',{},'JmodalEnergy',{},'JmodalPeak',{}, ...
    'JaccelerationRMS',{},'JaccelerationPeak',{}, ...
    'JjerkRMS',{},'JjerkPeak',{},'JresonanceBand',{}, ...
    'ResonanceBandEnergy',{},'ResonanceBandPSD',{}, ...
    'ResonanceBandReductionPercent',{}, ...
    'AccelerationRMSX',{},'AccelerationRMSY',{}, ...
    'AccelerationPeakX',{},'AccelerationPeakY',{}, ...
    'JerkRMSX',{},'JerkRMSY',{},'JerkPeakX',{},'JerkPeakY',{}, ...
    'Jstraightness',{},'Feasible',{},'Status',{});
current=warm;
for i=1:numel(weights)
    lv=weights(i); ls=1-lv;
    if i==1 && lv==0
        solution=warm;
    else
        spec=struct('stage','secondary','lambda_vibration',lv, ...
            'lambda_straightness',ls,'straightness_scale',straightScale, ...
            'vibration_scale',vibrationScale, ...
            'resonance_band_reference',bandReference.proxy, ...
            'resonance_band_reference_actual',bandReference.actual);
        solution=solve_fixed_Nvec(path,cfg,Nvec,current,spec);
    end
    solutions{i}=solution;
    if solution.feasible, current=solution; end
    components=solution.objectives.vibration_components;
    rows(end+1)=struct('LambdaVibration',lv,'LambdaStraightness',ls, ...
        'N',solution.N,'T',solution.T,'Jvibration',solution.objectives.vibration, ...
        'JmodalEnergy',cfg.objective.vibration_energy_weight*components.energy, ...
        'JmodalPeak',cfg.objective.vibration_peak_weight*components.peak_squared, ...
        'JaccelerationRMS',cfg.objective.acceleration_rms_weight*components.acceleration_rms, ...
        'JaccelerationPeak',cfg.objective.acceleration_peak_weight*components.acceleration_peak, ...
        'JjerkRMS',cfg.objective.jerk_rms_weight*components.jerk_rms, ...
        'JjerkPeak',cfg.objective.jerk_peak_weight*components.jerk_peak, ...
        'JresonanceBand',components.resonance_band_contribution, ...
        'ResonanceBandEnergy',components.resonance_band_energy, ...
        'ResonanceBandPSD',solution.validation.resonance_band.actual_total, ...
        'ResonanceBandReductionPercent',100*(bandReference.actual- ...
            solution.validation.resonance_band.actual_total)/bandReference.actual, ...
        'AccelerationRMSX',components.acceleration_rms_axis(1), ...
        'AccelerationRMSY',components.acceleration_rms_axis(2), ...
        'AccelerationPeakX',components.acceleration_peak_axis(1), ...
        'AccelerationPeakY',components.acceleration_peak_axis(2), ...
        'JerkRMSX',components.jerk_rms_axis(1), ...
        'JerkRMSY',components.jerk_rms_axis(2), ...
        'JerkPeakX',components.jerk_peak_axis(1), ...
        'JerkPeakY',components.jerk_peak_axis(2), ...
        'Jstraightness',solution.objectives.straightness,'Feasible',solution.feasible, ...
        'Status',string(solution.status)); %#ok<AGROW>
    fprintf(['  Pareto lambda_vib=%.2f: %s, Jvib=%.6g, Jline=%.6g, ' ...
        'band reduction=%.2f%%\n'],lv,local_state(solution.feasible), ...
        solution.objectives.vibration,solution.objectives.straightness, ...
        rows(end).ResonanceBandReductionPercent);
end
data=struct2table(rows);
end

function s=local_state(pass)
if pass, s='feasible'; else, s='infeasible'; end
end
