function comparison = build_comparison_table(s0,sA,sB,f0,fA,fB,cfg)
%BUILD_COMPARISON_TABLE Required three-solution research metrics.
solutions={s0,sA,sB}; freq={f0,fA,fB}; n=3;
frequencyLabel=sprintf('%g Hz',fB.mode(1).frequency);
bandEnergyX=string([frequencyLabel,' Band Energy X']);
bandEnergyY=string([frequencyLabel,' Band Energy Y']);
reductionLabel=string([frequencyLabel,' Energy Reduction [%]']);
metricNames=["Cycle Time [s]";"Time Increase vs Tmin [%]"; ...
    "Max Contour Error [mm]";"Contour RMSE [mm]";"Max Line Error [mm]"; ...
    "Max Corner Sagitta [mm]";"Max |Vx| [mm/s]";"Max |Vy| [mm/s]"; ...
    "Max |Ax| [mm/s^2]";"Max |Ay| [mm/s^2]";"Max |Jx| [mm/s^3]"; ...
    "Max |Jy| [mm/s^3]";"Max |Snapx| [mm/s^4]";"Max |Snapy| [mm/s^4]"; ...
    "Max |Cracklex| [mm/s^5]";"Max |Crackley| [mm/s^5]"; ...
    "Max |POPx| [mm/s^6]";"Max |POPy| [mm/s^6]"; ...
    "Straightness Objective";"Vibration Objective"; ...
    "Modal Energy Contribution";"Modal Peak Contribution"; ...
    "Acceleration RMS Contribution";"Acceleration Peak Contribution"; ...
    "Jerk RMS Contribution";"Jerk Peak Contribution"; ...
    "Resonance Band Contribution"; ...
    "Modal RMS X";"Modal RMS Y"; ...
    "Modal Peak X";"Modal Peak Y";bandEnergyX; ...
    bandEnergyY;reductionLabel; ...
    "Maximum Error Utilisation";"Mean Error Utilisation"; ...
    "Line Region Utilisation";"Corner Region Utilisation"];
values=nan(numel(metricNames),n);
for k=1:n
    s=solutions{k}; c=s.validation.contour; u=s.validation.usage;
    if s.model.n_modes>0
        mx=squeeze(s.modal(1,1,:)); my=squeeze(s.modal(2,1,:));
        modal=[rms(mx),rms(my),max(abs(mx)),max(abs(my))];
        be=[freq{k}.mode(1).band_energy.modal_x,freq{k}.mode(1).band_energy.modal_y];
    else
        modal=zeros(1,4); be=zeros(1,2);
    end
    vc=s.objectives.vibration_components;
    weightedComponents=[cfg.objective.vibration_energy_weight*vc.energy; ...
        cfg.objective.vibration_peak_weight*vc.peak_squared; ...
        cfg.objective.acceleration_rms_weight*vc.acceleration_rms; ...
        cfg.objective.acceleration_peak_weight*vc.acceleration_peak; ...
        cfg.objective.jerk_rms_weight*vc.jerk_rms; ...
        cfg.objective.jerk_peak_weight*vc.jerk_peak; ...
        vc.resonance_band_contribution];
    values(:,k)=[s.T;100*(s.T-s0.T)/s0.T;c.maximum;c.rmse;c.line_max; ...
        max([s.validation.corners.max_error]);u.peak(1,1);u.peak(1,2); ...
        u.peak(2,1);u.peak(2,2);u.peak(3,1);u.peak(3,2); ...
        u.peak(4,1);u.peak(4,2);u.peak(5,1);u.peak(5,2); ...
        u.peak(6,1);u.peak(6,2);s.objectives.straightness; ...
        s.objectives.vibration;weightedComponents;modal(:);be(:); ...
        NaN;c.maximum_utilisation;c.mean_utilisation; ...
        c.line_utilisation_mean;c.corner_utilisation_mean];
end
before=sum(values(32:33,2)); after=sum(values(32:33,3));
reduction=100*(before-after)/max(before,eps);
values(34,:)=[NaN,0,reduction];
comparison=table(metricNames,values(:,1),values(:,2),values(:,3), ...
    'VariableNames',{'Metric','Minimum_Time','No_Res_Suppression','Resonance_Suppression'});
end
