function results = resume_square_pop_moo(cfg)
%RESUME_SQUARE_POP_MOO Resume after Stage A from the latest feasible checkpoint.
root=fileparts(mfilename('fullpath')); addpath(genpath(root));
if nargin<1, cfg=trajectory_config(); end
if isempty(which('casadi.Opti'))
    error('POP_MOO:MissingCasADi','CasADi MATLAB interface is required.');
end
checkpoint=fullfile(cfg.output.mat,'stage_a_latest_feasible.mat');
if exist(checkpoint,'file')~=2
    error('POP_MOO:MissingCheckpoint','Stage A checkpoint not found: %s',checkpoint);
end
data=load(checkpoint,'latest');
if ~isfield(data,'latest')
    error('POP_MOO:InvalidCheckpoint','Checkpoint does not contain variable latest.');
end
switch lower(cfg.path.type)
    case 'square', path=generate_square_path(cfg);
    case 'csv', path=load_csv_path(cfg.path.csv_file,cfg.path.closed);
    otherwise, error('POP_MOO:BadPathType','Unsupported path type %s.',cfg.path.type);
end
solution_min_time=data.latest;
if ~isequal(size(solution_min_time.path.points),size(path.points)) || ...
        max(abs(solution_min_time.path.points-path.points),[],'all')>1e-12
    error('POP_MOO:CheckpointPathMismatch', ...
        'The saved Stage A checkpoint belongs to a different path.');
end
currentModel=build_augmented_dynamics(cfg);
if ~isequal(size(solution_min_time.model.Ad),size(currentModel.Ad)) || ...
        max(abs(solution_min_time.model.Ad-currentModel.Ad),[],'all')>1e-12 || ...
        max(abs(solution_min_time.model.Bd-currentModel.Bd),[],'all')>1e-12
    error('POP_MOO:CheckpointModelMismatch', ...
        'The saved Stage A checkpoint uses different Ts or resonance settings.');
end
solution_min_time.validation=validate_solution(solution_min_time,path,cfg);
if ~solution_min_time.validation.pass
    error('POP_MOO:CheckpointValidation', ...
        'The saved Stage A solution is incompatible with the current configuration.');
end
fprintf('Recovered Stage A: N=%d, T=%.3f s, Nvec=[%s]\n', ...
    solution_min_time.N,solution_min_time.T,num2str(solution_min_time.Nvec));
test_results=run_unit_tests(cfg);
stage_a_search=struct('history',table(),'seed_history',table(), ...
    'minimum_N',solution_min_time.N,'minimum_T',solution_min_time.T, ...
    'minimum_Nvec',solution_min_time.Nvec, ...
    'warm_start','Recovered from stage_a_latest_feasible.mat', ...
    'recovered_from',checkpoint);
[solution_no_resonance,solution_10Hz,pareto_data,pareto_solutions,stage_b_info]= ...
    solve_secondary_objectives(solution_min_time,path,cfg);
[time_sweep_solutions,time_sweep_data]=solve_all_time_vibration_sweep( ...
    solution_min_time,path,cfg,solution_no_resonance,pareto_solutions, ...
    pareto_data,stage_b_info);
artifacts=finalize_outputs(cfg,path,solution_min_time,solution_no_resonance, ...
    solution_10Hz,pareto_data,pareto_solutions,test_results,stage_a_search, ...
    stage_b_info,time_sweep_solutions,time_sweep_data);
results=struct('cfg',cfg,'path',path,'test_results',test_results, ...
    'solution_min_time',artifacts.solution_min_time, ...
    'solution_no_resonance',artifacts.solution_no_resonance, ...
    'solution_10Hz',artifacts.solution_10Hz, ...
    'solution_resonance_suppressed',artifacts.solution_resonance_suppressed, ...
    'solution_min_vibration',artifacts.solution_min_vibration, ...
    'comparison_table',artifacts.comparison_table,'pareto_data',pareto_data, ...
    'pareto_band_data',artifacts.pareto_band_data, ...
    'time_sweep_solutions',{artifacts.time_sweep_solutions}, ...
    'time_sweep_data',artifacts.time_sweep_data, ...
    'stage_a_search',stage_a_search,'stage_b_info',stage_b_info);
disp(results.comparison_table);
end
