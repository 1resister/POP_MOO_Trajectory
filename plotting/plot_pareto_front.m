function plot_pareto_front(data,cfg,solutionMin,solutionKnee,solutionMinVibration)
%PLOT_PARETO_FRONT Pareto scan with three representative solutions marked.
fig=figure('Visible',cfg.plot.visible,'Color','w'); valid=data.Feasible;
hScan=scatter(data.Jstraightness(valid),data.Jvibration(valid),60, ...
    data.LambdaVibration(valid),'filled','DisplayName','Near-time Pareto scan');
hold on; grid on; cb=colorbar; cb.Label.String='Vibration weight \lambda_{vib}';
handles=hScan; names={'Near-time Pareto scan'};
if nargin>=5
    hMin=plot(solutionMin.objectives.straightness,solutionMin.objectives.vibration, ...
        'p','MarkerSize',13,'MarkerFaceColor',[0.85 0.2 0.15], ...
        'MarkerEdgeColor','k','DisplayName',sprintf('Minimum time, N=%d',solutionMin.N));
    hKnee=plot(solutionKnee.objectives.straightness,solutionKnee.objectives.vibration, ...
        'd','MarkerSize',10,'MarkerFaceColor',[0.15 0.65 0.25], ...
        'MarkerEdgeColor','k','DisplayName','Knee point');
    hVib=plot(solutionMinVibration.objectives.straightness, ...
        solutionMinVibration.objectives.vibration,'s','MarkerSize',10, ...
        'MarkerFaceColor',[0.55 0.25 0.75],'MarkerEdgeColor','k', ...
        'DisplayName','Minimum vibration');
    handles=[handles,hMin,hKnee,hVib];
    names=[names,{'Minimum time','Knee point','Minimum vibration'}];
end
xlabel('Straightness objective [-]'); ylabel('Vibration objective [-]');
title('Pareto front and representative solutions'); legend(handles,names,'Location','best');
save_publication_figure(fig,fullfile(cfg.output.figures,'17_pareto_front.png'),cfg);
end
