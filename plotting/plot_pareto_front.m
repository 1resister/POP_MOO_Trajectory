function plot_pareto_front(data,cfg,solutionMin,solutionKnee,solutionMinVibration)
%PLOT_PARETO_FRONT Machining-time/vibration Pareto front.
fig=figure('Visible',cfg.plot.visible,'Color','w');
valid=data.Feasible;
front=data.ParetoOptimal;
hold on; grid on;
hNo=plot(data.Time_s(valid),data.NoSuppressionJvibration(valid), ...
    '--','Color',[0.55 0.55 0.55],'LineWidth',1.0, ...
    'DisplayName','No-suppression reference');
hCandidates=scatter(data.Time_s(valid),data.Jvibration(valid),35, ...
    [0.65 0.75 0.90],'filled','DisplayName','Fixed-time candidates');
[frontTime,order]=sort(data.Time_s(front));
frontVibration=data.Jvibration(front);
frontVibration=frontVibration(order);
hFront=plot(frontTime,frontVibration,'-o','Color',[0.10 0.35 0.75], ...
    'MarkerFaceColor',[0.10 0.35 0.75],'LineWidth',1.4, ...
    'DisplayName','Time-vibration Pareto front');
handles=[hNo,hCandidates,hFront];
names={'No-suppression reference','Fixed-time candidates', ...
    'Time-vibration Pareto front'};
if nargin>=5
    hMin=plot(solutionMin.T,solutionMin.objectives.vibration,'p', ...
        'MarkerSize',13,'MarkerFaceColor',[0.85 0.2 0.15], ...
        'MarkerEdgeColor','k','DisplayName','Minimum time');
    hKnee=plot(solutionKnee.T,solutionKnee.objectives.vibration,'d', ...
        'MarkerSize',10,'MarkerFaceColor',[0.15 0.65 0.25], ...
        'MarkerEdgeColor','k','DisplayName','Knee point');
    hVib=plot(solutionMinVibration.T,solutionMinVibration.objectives.vibration, ...
        's','MarkerSize',10,'MarkerFaceColor',[0.55 0.25 0.75], ...
        'MarkerEdgeColor','k','DisplayName','Minimum vibration');
    handles=[handles,hMin,hKnee,hVib];
    names=[names,{'Minimum time','Knee point','Minimum vibration'}];
end
xlabel('Machining time T [s]');
ylabel('Vibration objective J_{vib} [-]');
title('Machining-time and vibration Pareto front');
legend(handles,names,'Location','best');
save_publication_figure(fig,fullfile(cfg.output.figures,'17_pareto_front.png'),cfg);
end
