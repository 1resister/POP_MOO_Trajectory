function tableOut = save_trajectory_csv(solution,filename)
%SAVE_TRAJECTORY_CSV Persist every 1 ms node and required physical columns.
c=solution.validation.contour; N=solution.N;
pop=[solution.U,solution.U(:,end)];
if solution.model.n_modes>0
    modalX=squeeze(solution.modal(1,1,:)); modalY=squeeze(solution.modal(2,1,:));
else
    modalX=zeros(N+1,1); modalY=modalX;
end
tableOut=table(solution.time(:),solution.position(1,:).',solution.position(2,:).', ...
    solution.velocity(1,:).',solution.velocity(2,:).', ...
    solution.acceleration(1,:).',solution.acceleration(2,:).', ...
    solution.jerk(1,:).',solution.jerk(2,:).', ...
    solution.snap(1,:).',solution.snap(2,:).', ...
    solution.crackle(1,:).',solution.crackle(2,:).', ...
    pop(1,:).',pop(2,:).',c.error,c.allowed_error,c.utilisation,modalX,modalY, ...
    'VariableNames',{'time','x','y','vx','vy','ax','ay','jx','jy', ...
    'snapx','snapy','cracklex','crackley','POPx','POPy','contour_error', ...
    'allowed_error','error_utilisation','modal_x','modal_y'});
writetable(tableOut,filename);
end
